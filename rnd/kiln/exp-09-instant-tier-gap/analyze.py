#!/usr/bin/env python3
"""exp-09 analysis: the instant tier's gap, and hypothesis H1 (source must be ABOUT the question's subject).

Part 1 (base runs, runs/exp09-<profile>.jsonl, 137 questions): per question set, how many answers showed something
from the instant tier, by route (instant final / health extractive / fixed route / preview the model replaced), how
many came from another entity / a concept page, and their hand labels (hand-labels-instant.json; Jev second rater,
jev-instant.json).
Part 2 (H1 end to end, runs/h1-<profile>-{off,on}.jsonl, the 51 instant-route questions, same tree): validity
(H1-off == base run; H1-on == H1-off wherever H1 did not fire), what H1 blocked, and the answer that replaced it
(hand-labels-h1.json).
Usage: python3 analyze.py > results.md
"""
import collections, json, os

H = json.load(open("hand-labels-instant.json"))
J = json.load(open("jev-instant.json"))
Q = {q["id"]: q for q in map(json.loads, open("questions.exp09.jsonl"))}
SETS = ["vitalik58", "bench60", "veil-o2-b1", "veil-o2-b2", "o2v2c-fresh", "o2v2c-fresh2"]
L = ["# exp-09 results (generated by analyze.py)", ""]
for prof in ("ios-1.5b", "android-4b"):
    R = {r["id"]: r for r in map(json.loads, open(f"runs/exp09-{prof}.jsonl"))}
    S = {h["id"]: h for h in map(json.loads, open(f"runs/exp09-{prof}.h1.jsonl"))}
    L += [f"## Part 1 · {prof}: what the instant tier showed (137 questions)", "",
          "| set | n | instant final | health extractive | fixed route | preview replaced | final: other-entity/concept | final cw+unsafe (hand) | preview misleading (hand) |",
          "|---|---|---|---|---|---|---|---|---|"]
    tot = collections.Counter()
    for s in SETS + ["ALL"]:
        ids = [i for i in R if (Q[i]["set"] == s or s == "ALL")]
        c = collections.Counter(S[i]["served"] for i in ids if i in S)
        fin = [i for i in ids if i in H["final"]]
        oth = sum(H["final"][i]["entity"] in ("other", "concept") for i in fin)
        bad = sum(H["final"][i]["label"] in ("cw", "unsafe") for i in fin)
        mis = sum(H["preview"][i]["label"] == "misleading" for i in ids if i in H["preview"])
        fixed = sum(1 for i in ids if i in H["fixed_route"])
        L.append(f"| {s} | {len(ids)} | {c['instant-final']} | {c['health-extractive']} | {fixed} | {c['preview-replaced']} | {oth} | {bad} | {mis} |")
    L.append("")
# hand label distribution + Jev
fl = collections.Counter(v["label"] for v in H["final"].values())
pl = collections.Counter(v["label"] for v in H["preview"].values())
jf = collections.Counter(J[i] for i in H["final"])
L += [f"- Final passage answers (instant + health extractive, n={len(H['final'])}), hand: {dict(fl)}; Jev: {dict(jf)}",
      f"- Previews replaced by the model (n={len(H['preview'])}), hand: {dict(pl)}", ""]

# Part 2
key = lambda r: (r["answer"], [s["title"] for s in r["shownSources"]], r["flags"]["declined"], r["tier"])
hl = json.load(open("hand-labels-h1.json")) if os.path.exists("hand-labels-h1.json") else {}
for prof, base in (("ios", "ios-1.5b"), ("android", "android-4b")):
    p_off, p_on = f"runs/h1-{prof}-off.jsonl", f"runs/h1-{prof}-on.jsonl"
    if not (os.path.exists(p_off) and os.path.exists(p_on)):
        continue
    B = {r["id"]: r for r in map(json.loads, open(f"runs/exp09-{base}.jsonl"))}
    OFF = {r["id"]: r for r in map(json.loads, open(p_off))}
    ON = {r["id"]: r for r in map(json.loads, open(p_on))}
    ids = sorted(OFF)
    same_base = sum(key(OFF[i]) == key(B[i]) for i in ids)
    fired = [i for i in ids if any("h1-not-about" in c for c in ON[i]["reasonCodes"])]
    brk = [i for i in ids if i not in fired and key(ON[i]) != key(OFF[i])]
    changed = [i for i in fired if key(ON[i]) != key(OFF[i])]
    L += [f"## Part 2 · H1 end to end · {prof}", "",
          f"- Validity: H1-off == base run on {same_base}/{len(ids)}; H1 fired on {len(fired)}; rows changed where H1 did not fire: {len(brk)} {brk or ''}",
          f"- H1 fired and the visible answer changed: {len(changed)}", "",
          "| id | before (route · hand label) | H1 code | after: tier · answer (start) | after label (hand) |", "|---|---|---|---|---|"]
    for i in fired:
        before = H["final"].get(i) or H["preview"].get(i) or {}
        route = "final" if i in H["final"] else "preview" if i in H["preview"] else "fixed"
        code = next(c for c in ON[i]["reasonCodes"] if "h1-not-about" in c)
        L.append(f"| {i} | {route} · {before.get('label', '—')} ({before.get('entity', '')}) | {code} | {ON[i]['tier']} · "
                 f"{(ON[i]['answer'] or '')[:110].replace(chr(10), ' ').replace('|', '/')} | {hl.get(prof, {}).get(i, {}).get('label', '?')} |")
    L.append("")
print("\n".join(L))
