#!/usr/bin/env python3
"""Derive eval/runner/kiln-capture.ts from the eval runner (boar-app feat/eval-frontier, eval/runner/desktop.ts).

kiln-capture runs the app's real answer pipeline (--pipeline app --retrieval app: classifier, retrieval, packs,
sentence compression, prompt assembly) but does NOT generate: the engine's generate() records the exact
messages/prompt/nPredict the app would send to llama.rn and returns a placeholder. The captured contexts are then
replayed, identical, to every model through llama-server (serve-bench.py).

Every patch must apply exactly once, so a runner change upstream fails loudly instead of silently.
Usage: python3 make-capture.py <tree>/eval/runner/desktop.ts <tree>/eval/runner/kiln-capture.ts
"""
import sys

src_path, out_path = sys.argv[1], sys.argv[2]
s = open(src_path).read()

PATCHES = [
    # 1. CLI flags: --questions <jsonl>, --tier <answerTier>, --capture
    ('    out: get("--out"),\n',
     '    out: get("--out"),\n    questions: get("--questions"),\n    tier: get("--tier"),\n    capture: a.includes("--capture"),\n'),
    # 2. capture mode does not need (or hash) the chat model file
    ('  const modelPath = join(SHARED_MODELS, spec.file);\n  if (!existsSync(modelPath)) throw new Error(`missing ${modelPath}`);\n  await verifyModel(modelPath, spec.sha256);\n',
     '  const modelPath = join(SHARED_MODELS, spec.file);\n  if (!opt.capture) {\n  if (!existsSync(modelPath)) throw new Error(`missing ${modelPath}`);\n  await verifyModel(modelPath, spec.sha256);\n  }\n'),
    # 3. questions from any jsonl (Lantern's handoff set) instead of eval/dataset only
    ('readFileSync(join(EVAL_DIR, `dataset/questions.${opt.dataset}.jsonl`), "utf8")',
     'readFileSync(opt.questions ?? join(EVAL_DIR, `dataset/questions.${opt.dataset}.jsonl`), "utf8")'),
    # 4. no chat model load in capture mode; pretend it has an embedded chat template (llama.rn path = messages)
    ('  const model = await llama.loadModel({ modelPath, gpuLayers: opt.gpu ? "auto" : 0, useMlock: false });\n',
     '  const model: any = opt.capture ? { fileInfo: { metadata: { tokenizer: { chat_template: "kiln-capture" } } } } : await llama.loadModel({ modelPath, gpuLayers: opt.gpu ? "auto" : 0, useMlock: false });\n'),
    # 5. same answer tier for every model (the reader comparison must not change the app's route)
    ('      answerTier: entry?.answerTier ?? "default",\n',
     '      answerTier: opt.tier ?? entry?.answerTier ?? "default",\n'),
    # 6. generate(): record what the app sends, return a placeholder
    ('        async generate(o: any) {\n',
     '        async generate(o: any) {\n'
     '          if (opt.capture) {\n'
     '            const params: Record<string, unknown> = {};\n'
     '            for (const [k, v] of Object.entries(o)) if (typeof v !== "function" && k !== "messages" && k !== "prompt") params[k] = v;\n'
     '            kilnCaptured.push({ messages: o.messages, prompt: o.prompt, nPredict: o.nPredict, params });\n'
     '            lastGen = { answer: "(kiln-capture)", reasoning: "", reasoningTokens: 0, firstTokenMs: 0, ttftMs: 0, generationLatencyMs: 1, tokensGenerated: 1, timedOut: false, promptFormat: "chat-template" };\n'
     '            o.onToken?.(lastGen.answer);\n'
     '            return lastGen.answer;\n'
     '          }\n'),
    # 7. per-question capture buffer
    ('        lastGen = undefined; lastChunks = []; promptChunks = [];\n',
     '        lastGen = undefined; lastChunks = []; promptChunks = []; kilnCaptured = [];\n'),
    ('  let first = true;\n  for (const q of questions) {\n',
     '  let first = true;\n  for (const q of questions) {\n'),
    ('  let answerer: any = null, appCtx: any = null,',
     '  let kilnCaptured: any[] = [];\n  let answerer: any = null, appCtx: any = null,'),
    # 8. write the captured calls into the row
    ('      seed: opt.seed,\n',
     '      seed: opt.seed,\n      kilnCaptured: opt.capture ? kilnCaptured : undefined,\n'),
]

for old, new in PATCHES:
    n = s.count(old)
    if n != 1:
        sys.exit(f"patch anchor found {n} times (expected 1):\n{old[:120]}")
    s = s.replace(old, new)

banner = "// GENERATED by rnd/kiln/exp-01-inram-moe-reader/harness/make-capture.py from desktop.ts. Do not edit.\n"
if s.startswith("#!"):
    nl = s.index("\n") + 1
    s = s[:nl] + banner + s[nl:]
else:
    s = banner + s
open(out_path, "w").write(s)
print(f"wrote {out_path} ({len(PATCHES)} patches)")
