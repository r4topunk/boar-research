#!/usr/bin/env python3
"""exp-10 analysis: main 6b53ee83 (old engine) vs the new engine (611a4b92, exp-09 runs), same desktop harness family,
greedy, kit A, two profiles.

1. Determinism of the main runs (run vs -rep).
2. Route profile of main: task types, plan steps, how many answers had 0 sources, which packs the sources came from.
3. Safety (Lantern's safety_check v0.3): track saf-001..012 + the bench danger items (overlay v0.3), per engine and
   profile: unsafe hits, with the sentence. New engine rows: runs/new-<profile>-safety.jsonl (track) + exp-09 runs (bench).
4. Bench quality proxy: Lantern precheck v2.2 on the 60 public items, main vs new engine (same profile).
Usage: python3 analyze.py > results.md
"""
import collections, json, os, subprocess, sys, tempfile

B = "<workspace>"
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, f"{B}/rnd/bench/safety")
import safety_check as SC

S = SC.load(version="v0.3")
TRACK = {q["id"]: q for q in map(json.loads, open(f"{B}/rnd/bench/safety/track.v0.3.jsonl"))}
BENCH = {q["id"]: q for q in map(json.loads, open(f"{B}/rnd/bench/questions/v0/questions.public.jsonl"))}
DANGER = {i: q for i, q in {**BENCH, **TRACK}.items() if SC.rules_for(q, S)}
load = lambda p: {r["id"]: r for r in map(json.loads, open(p))} if os.path.exists(p) else {}
key = lambda r: (r["answer"], [s["title"] for s in r["sources"]])
PROF = {"ios": ("main-ios-1.5b", "exp09-ios-1.5b"), "android": ("main-android-4b", "exp09-android-4b")}
L = ["# exp-10 results (generated by analyze.py)", ""]
summary = {}
for prof, (mainrun, newrun) in PROF.items():
    M, Mr = load(f"{HERE}/runs/{mainrun}.jsonl"), load(f"{HERE}/runs/{mainrun}-rep.jsonl")
    N = {**load(f"{B}/rnd/kiln/exp-09-instant-tier-gap/runs/{newrun}.jsonl"), **load(f"{HERE}/runs/new-{prof}-safety.jsonl")}
    if not M:
        continue
    det = sum(key(M[i]) == key(Mr[i]) for i in M if i in Mr)
    tt = collections.Counter(r["taskType"] for r in M.values())
    steps = collections.Counter(",".join(s.split(":")[0] for s in r["planSteps"]) for r in M.values())
    zero = sum(not r["sources"] for r in M.values())
    src_titles = [s["title"] for r in M.values() for s in r["sources"]]
    fb = sum(r["route"] != "adaptive" for r in M.values())
    errs = [r["id"] for r in M.values() if r["error"]]
    L += [f"## {prof}", "",
          f"- determinism (run vs repeat, answer + sources): **{det}/{len(M)}**; errors: {errs or 0}; ChatScreen fallback used: {fb}",
          f"- task types: {dict(tt)}; plan step shapes: {dict(steps)}",
          f"- answers with 0 sources: {zero}/{len(M)}; sources from Wikivoyage/crypto titles: "
          f"{sum(t.startswith(('Wikivoyage', 'Ethereum', 'Bitcoin', 'ethereum.org')) for t in src_titles)} of {len(src_titles)}", "",
          "### Safety (safety_check v0.3; danger items = track saf-001..012 + bench items with overlay rules)", "",
          "| id | rules | main (old engine) | new engine (611a4b92) |", "|---|---|---|---|"]
    tot = {"main": 0, "new": 0}
    for i in sorted(DANGER):
        q = DANGER[i]
        rules = SC.rules_for(q, S)
        cells = []
        for tag, R in (("main", M), ("new", N)):
            r = R.get(i)
            if not r:
                cells.append("—")
                continue
            hits = SC.check(r["answer"], rules, S)
            unsafe = [h for h in hits if not h["match"].startswith("MISSING")]
            miss = [h for h in hits if h["match"].startswith("MISSING")]
            tot[tag] += bool(unsafe)
            cells.append(("**UNSAFE** " + "; ".join(f"{h['rule']}: “{h['sentence'][:90]}”" for h in unsafe) if unsafe else "ok")
                         + (f" (omits: {', '.join(h['rule'] for h in miss)})" if miss else ""))
        L.append(f"| {i} | {', '.join(rules)} | {cells[0]} | {cells[1]} |")
    L += ["", f"- **unsafe answers: main {tot['main']} / new engine {tot['new']}** (of {len(DANGER)} danger items)", ""]
    summary[prof] = {"determinism": det, "n": len(M), "unsafe_main": tot["main"], "unsafe_new": tot["new"], "zero_sources": zero}
    # precheck v2.2 on the 60 public items, main vs new
    LT = f"{B}/rnd/lantern"
    def precheck(R):
        rows = [R[i] for i in BENCH if i in R]
        with tempfile.TemporaryDirectory() as d:
            f, js = f"{d}/r.jsonl", f"{d}/o.json"
            with open(f, "w") as fh:
                for r in rows:
                    fh.write(json.dumps({"queryId": r["id"], "answer": r["answer"], "declined": bool(r.get("flags", {}).get("declined"))}) + "\n")
            json.dump({"ids": [r["id"] for r in rows]}, open(f"{d}/s.json", "w"))
            subprocess.run(["python3", f"{LT}/tools/precheck.py", f, "--subset", f"{d}/s.json", "--json", js], cwd=LT, check=True, capture_output=True)
            return collections.Counter(x["status"] for x in json.load(open(js)))
    pm, pn = precheck(M), precheck(N)
    L += [f"### Bench v0 public 60, precheck v2.2 (free pre-pass, not the bench score)", "",
          f"- main: {dict(pm)}", f"- new engine: {dict(pn)}", ""]
    summary[prof]["precheck"] = {"main": dict(pm), "new": dict(pn)}
print("\n".join(L))
json.dump(summary, open(f"{HERE}/results.json", "w"), indent=1)
