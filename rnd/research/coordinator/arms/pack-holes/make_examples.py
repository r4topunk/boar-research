#!/usr/bin/env python3 -I
"""out/<pack>.json -> EXAMPLES.md (10 reservoir-sampled examples per pattern, per pack)."""
import json, os
here = os.path.dirname(os.path.abspath(__file__))
lines = ["# Hole examples (10 per pattern, reservoir-sampled, seed 7)\n", "Generated by make_examples.py from out/*.json; context = 70 chars before / 40 after the match.\n"]
for n in ["boar-simplewiki-en", "boar-wikivoyage-en", "boar-firstaid-en", "boar-wiki-en-top100k"]:
    d = json.load(open(f"{here}/out/{n}.json"))
    lines.append(f"\n## {n}  ({d['chunks_scanned']} chunks scanned, strong {d['share_strong']:.2%}, fact {d['share_fact']:.2%})\n")
    for k, v in sorted(d["per_pattern"].items(), key=lambda x: -x[1]):
        if k in ("double_space",): continue
        lines.append(f"\n### {k}: {v} chunks ({v / d['chunks_scanned']:.2%})\n")
        for e in d["examples"].get(k, []):
            lines.append("- `" + e["title"].replace("`", "'") + "`: " + e["ctx"].replace("`", "'").replace("|", "/") )
open(f"{here}/EXAMPLES.md", "w").write("\n".join(lines) + "\n")
